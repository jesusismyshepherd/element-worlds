// Writes src/chem/orbitalSkins.js: every orbital's 90 % skin (the density on it and how far out it reaches)
// for a nuclear charge of 1, from 200 000 places drawn by Born's rule. Hydrogen's orbitals scale exactly
// with the charge (the density on the skin goes as Z³, its reach as 1/Z), so this one table serves every
// subshell of every element at no cost while playing. Run: node scripts/data/orbital_skins.mjs
import { writeFileSync, renameSync } from 'node:fs'
import { HARMONICS, finder, psi, random } from '../../src/chem/orbitals.js'

const N = 200000
const rows = []
for (let n = 1; n <= 7; n++) {
  for (let lq = 0; lq < Math.min(n, 4); lq++) {
    for (const h of HARMONICS[lq]) {
      const o = { n, lq, k: h.k }
      const find = finder(o, 1, random(1000 + n * 97 + h.k * 13))
      const d = new Float64Array(N)
      const r = new Float64Array(N)
      for (let i = 0; i < N; i++) {
        const [x, y, z] = find()
        const v = psi(o, 1, x, y, z)
        d[i] = v * v
        r[i] = Math.hypot(x, y, z)
      }
      const level = Float64Array.from(d).sort()[Math.floor(N * 0.1)]
      let reach = 0
      for (let i = 0; i < N; i++) if (d[i] >= level) reach = Math.max(reach, r[i])
      rows.push(`  '${n},${h.k}': [${level.toPrecision(6)}, ${reach.toPrecision(5)}],`)
    }
  }
}
const text = `// Generated by scripts/data/orbital_skins.mjs (do not edit): for each orbital 'n,k' (k: the harmonic's
// index in orbitals.js), the density on its 90 % skin and the skin's farthest reach (a0), for a nuclear
// charge of 1. For a charge Z the density is Z³ times this and the reach 1/Z of it.
export const SKINS = {
${rows.join('\n')}
}
`
const out = new URL('../../src/chem/orbitalSkins.js', import.meta.url)
const tmp = new URL('../../src/chem/orbitalSkins.js.tmp', import.meta.url)
writeFileSync(tmp, text)
renameSync(tmp, out)
console.log(`${rows.length} orbitals written`)
